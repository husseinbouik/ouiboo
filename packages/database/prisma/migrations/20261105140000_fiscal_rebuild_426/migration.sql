-- #426 (Council P0-10): fiscal rebuild of fees & invoices.
-- Expand-mostly: Invoice gains a document class (INVOICE / CREDIT_NOTE),
-- the issuer IF, and a TVA snapshot (rate / amount / TTC total);
-- InvoiceLineItem gains the per-line TVA breakdown, a line type
-- (SERVICE_FEE / SUBSCRIPTION), a nullable booking (subscription lines
-- carry none) and the refund-case link that makes credit-note
-- generation idempotent; InvoiceSequence gains a per-class series so
-- avoirs number independently (AV-) from invoices (INV-).
--
-- The TVA columns default to the council's working assumption
-- (20% rate, amounts 0 until a document is generated by the new code):
-- the rate is PENDING WRITTEN CONFIRMATION from the expert-comptable
-- and is configurable in the application (OUIBOO_VAT_RATE_PERCENT).
-- Existing invoice rows are historical test documents: their vatAmount
-- / totalTtcAmount stay 0 rather than being backfilled with a rate
-- nobody had confirmed when they were issued.
--
-- The (agencyId, periodStart, periodEnd) unique is replaced by a
-- nullable periodKey unique set only on INVOICE documents: the old
-- constraint could not represent a credit note for the same agency and
-- month as its invoice. Existing rows are backfilled deterministically.
--
-- Rollback: drop periodKey + its index, restore the old unique (only
-- valid while no CREDIT_NOTE rows exist), drop the added columns and
-- types, and restore InvoiceSequence's single-column primary key
-- (only valid while no CREDIT_NOTE sequence rows exist).

-- New enums
CREATE TYPE "InvoiceDocumentType" AS ENUM ('INVOICE', 'CREDIT_NOTE');
CREATE TYPE "InvoiceLineType" AS ENUM ('SERVICE_FEE', 'SUBSCRIPTION');

-- InvoiceStatus gains CREDITED (cannot be removed in place on rollback;
-- harmless if left: no pre-#426 code writes it)
ALTER TYPE "InvoiceStatus" ADD VALUE 'CREDITED';

-- Invoice: document class, issuer IF, TVA snapshot, credit-note link
ALTER TABLE "Invoice" ADD COLUMN "documentType" "InvoiceDocumentType" NOT NULL DEFAULT 'INVOICE';
ALTER TABLE "Invoice" ADD COLUMN "issuerIf" TEXT;
ALTER TABLE "Invoice" ADD COLUMN "vatRate" DECIMAL(5,2) NOT NULL DEFAULT 20;
ALTER TABLE "Invoice" ADD COLUMN "vatAmount" DECIMAL(18,2) NOT NULL DEFAULT 0;
ALTER TABLE "Invoice" ADD COLUMN "totalTtcAmount" DECIMAL(18,2) NOT NULL DEFAULT 0;
ALTER TABLE "Invoice" ADD COLUMN "creditNoteForId" TEXT;
ALTER TABLE "Invoice" ADD COLUMN "creditReason" TEXT;
ALTER TABLE "Invoice" ADD COLUMN "periodKey" TEXT;

ALTER TABLE "Invoice" ADD CONSTRAINT "Invoice_creditNoteForId_fkey"
  FOREIGN KEY ("creditNoteForId") REFERENCES "Invoice"("id") ON DELETE SET NULL ON UPDATE CASCADE;

CREATE UNIQUE INDEX "Invoice_periodKey_key" ON "Invoice"("periodKey");
CREATE INDEX "Invoice_documentType_agencyId_idx" ON "Invoice"("documentType", "agencyId");

-- Backfill the idempotency key for existing INVOICE documents, then
-- drop the superseded (agency, period) unique.
UPDATE "Invoice"
SET "periodKey" = "agencyId" || ':' || to_char("periodStart" AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS".000Z"')
WHERE "documentType" = 'INVOICE';
DROP INDEX "Invoice_agencyId_periodStart_periodEnd_key";

-- InvoiceLineItem: per-line TVA, line type, refund-case link, nullable booking
ALTER TABLE "InvoiceLineItem" ADD COLUMN "lineType" "InvoiceLineType" NOT NULL DEFAULT 'SERVICE_FEE';
ALTER TABLE "InvoiceLineItem" ADD COLUMN "refundCaseId" TEXT;
ALTER TABLE "InvoiceLineItem" ADD COLUMN "amountHt" DECIMAL(18,2) NOT NULL DEFAULT 0;
ALTER TABLE "InvoiceLineItem" ADD COLUMN "vatRate" DECIMAL(5,2) NOT NULL DEFAULT 20;
ALTER TABLE "InvoiceLineItem" ADD COLUMN "vatAmount" DECIMAL(18,2) NOT NULL DEFAULT 0;
ALTER TABLE "InvoiceLineItem" ADD COLUMN "amountTtc" DECIMAL(18,2) NOT NULL DEFAULT 0;
ALTER TABLE "InvoiceLineItem" ALTER COLUMN "bookingId" DROP NOT NULL;
CREATE INDEX "InvoiceLineItem_refundCaseId_idx" ON "InvoiceLineItem"("refundCaseId");

-- Backfill line HT from the historical fee amount (fee lines only ever
-- existed pre-#426, and their commissionAmount IS their HT).
UPDATE "InvoiceLineItem" SET "amountHt" = "commissionAmount", "amountTtc" = "commissionAmount";

-- InvoiceSequence: one series per document class
ALTER TABLE "InvoiceSequence" ADD COLUMN "kind" "InvoiceDocumentType" NOT NULL DEFAULT 'INVOICE';
ALTER TABLE "InvoiceSequence" DROP CONSTRAINT "InvoiceSequence_pkey";
ALTER TABLE "InvoiceSequence" ADD CONSTRAINT "InvoiceSequence_pkey" PRIMARY KEY ("year", "kind");
